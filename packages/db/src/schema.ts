import { bigint, index, integer, pgTable, primaryKey, text } from "drizzle-orm/pg-core";

/** All timestamps are epoch milliseconds. */

export const users = pgTable("users", {
  id: text("id").primaryKey(),
  email: text("email").notNull().unique(),
  /** Decides features only. It never affects redirects. See PLANS in @stillscans/shared. */
  plan: text("plan", { enum: ["free", "pro", "business"] })
    .notNull()
    .default("free"),
  /** Dynamic codes this account may hold. Free is 5; Pro raises it to 100. */
  codeAllowance: integer("code_allowance").notNull().default(5),
  createdAt: bigint("created_at", { mode: "number" }).notNull(),
});

export const sessions = pgTable(
  "sessions",
  {
    /** SHA-256 of the bearer token: a database leak must not yield usable sessions. */
    tokenHash: text("token_hash").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: bigint("expires_at", { mode: "number" }).notNull(),
    createdAt: bigint("created_at", { mode: "number" }).notNull(),
  },
  (t) => [index("sessions_expires_at_idx").on(t.expiresAt)],
);

export const codes = pgTable(
  "codes",
  {
    id: text("id").primaryKey(),
    /** Unique forever, including archived rows: a printed code is never reassigned. */
    shortCode: text("short_code").notNull().unique(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id),
    label: text("label"),
    destination: text("destination").notNull(),
    /** JSON QrDesign: how the code looks when downloaded. Never affects the redirect. */
    design: text("design"),
    status: text("status", { enum: ["active", "paused", "blocked", "archived"] })
      .notNull()
      .default("active"),
    /** Bumped on every change that affects the KV record. */
    version: integer("version").notNull().default(1),
    /** Version last written to KV. Rows where this lags `version` are retried by cron. */
    syncedVersion: integer("synced_version").notNull().default(0),
    createdAt: bigint("created_at", { mode: "number" }).notNull(),
    updatedAt: bigint("updated_at", { mode: "number" }).notNull(),
  },
  (t) => [
    index("codes_user_id_idx").on(t.userId),
    index("codes_sync_idx").on(t.syncedVersion, t.version),
  ],
);

export const codeDestinations = pgTable(
  "code_destinations",
  {
    id: text("id").primaryKey(),
    codeId: text("code_id")
      .notNull()
      .references(() => codes.id),
    destination: text("destination").notNull(),
    createdAt: bigint("created_at", { mode: "number" }).notNull(),
  },
  (t) => [index("code_destinations_code_id_idx").on(t.codeId, t.createdAt)],
);

/** No foreign key: the scan path must keep working regardless of the codes table. */
export const scans = pgTable(
  "scans",
  {
    /** Generated by redirect. Dedupes the queue's at-least-once delivery. */
    id: text("id").primaryKey(),
    shortCode: text("short_code").notNull(),
    scannedAt: bigint("scanned_at", { mode: "number" }).notNull(),
    country: text("country"),
    region: text("region"),
    city: text("city"),
    deviceType: text("device_type", { enum: ["mobile", "desktop", "unknown"] }).notNull(),
    os: text("os", { enum: ["ios", "android", "windows", "mac", "other"] })
      .notNull()
      .default("other"),
    visitorHash: text("visitor_hash"),
  },
  (t) => [index("scans_short_code_idx").on(t.shortCode, t.scannedAt)],
);

/** Check results. Private by unguessable id; deleted by cron after 30 days. */
export const checks = pgTable(
  "checks",
  {
    id: text("id").primaryKey(),
    /** SHA-256 of the input, for the short-lived result cache. */
    inputHash: text("input_hash").notNull(),
    result: text("result").notNull(),
    createdAt: bigint("created_at", { mode: "number" }).notNull(),
  },
  (t) => [
    index("checks_input_hash_idx").on(t.inputHash, t.createdAt),
    index("checks_created_at_idx").on(t.createdAt),
  ],
);

export const providerReports = pgTable("provider_reports", {
  id: text("id").primaryKey(),
  providerSlug: text("provider_slug"),
  domain: text("domain"),
  message: text("message").notNull(),
  email: text("email"),
  status: text("status", { enum: ["open", "resolved"] })
    .notNull()
    .default("open"),
  createdAt: bigint("created_at", { mode: "number" }).notNull(),
});

/** People asking to hear when a paid plan opens. */
export const waitlist = pgTable(
  "waitlist",
  {
    email: text("email").notNull(),
    plan: text("plan", { enum: ["pro", "business"] }).notNull(),
    source: text("source"),
    createdAt: bigint("created_at", { mode: "number" }).notNull(),
  },
  (t) => [primaryKey({ columns: [t.email, t.plan] })],
);

/** Redirect domains seen by the checker but missing from the directory: the research queue. */
export const unknownDomains = pgTable(
  "unknown_domains",
  {
    domain: text("domain").notNull(),
    firstSeen: bigint("first_seen", { mode: "number" }).notNull(),
    lastSeen: bigint("last_seen", { mode: "number" }).notNull(),
    count: integer("count").notNull().default(1),
  },
  (t) => [primaryKey({ columns: [t.domain] })],
);
