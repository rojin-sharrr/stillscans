import { index, integer, primaryKey, sqliteTable, text } from "drizzle-orm/sqlite-core";

/** All timestamps are epoch milliseconds. */

export const users = sqliteTable("users", {
  id: text("id").primaryKey(),
  email: text("email").notNull().unique(),
  /** Dynamic codes this account may hold. Free is 3; one-time packs raise it. */
  codeAllowance: integer("code_allowance").notNull().default(3),
  createdAt: integer("created_at").notNull(),
});

export const sessions = sqliteTable(
  "sessions",
  {
    /** SHA-256 of the bearer token: a database leak must not yield usable sessions. */
    tokenHash: text("token_hash").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: integer("expires_at").notNull(),
    createdAt: integer("created_at").notNull(),
  },
  (t) => [index("sessions_expires_at_idx").on(t.expiresAt)],
);

export const codes = sqliteTable(
  "codes",
  {
    id: text("id").primaryKey(),
    /** Unique forever, including archived rows: a printed code is never reassigned. */
    shortCode: text("short_code").notNull().unique(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id),
    label: text("label"),
    destination: text("destination").notNull(),
    status: text("status", { enum: ["active", "paused", "blocked", "archived"] })
      .notNull()
      .default("active"),
    /** Bumped on every change that affects the KV record. */
    version: integer("version").notNull().default(1),
    /** Version last written to KV. Rows where this lags `version` are retried by cron. */
    syncedVersion: integer("synced_version").notNull().default(0),
    createdAt: integer("created_at").notNull(),
    updatedAt: integer("updated_at").notNull(),
  },
  (t) => [
    index("codes_user_id_idx").on(t.userId),
    index("codes_sync_idx").on(t.syncedVersion, t.version),
  ],
);

export const codeDestinations = sqliteTable(
  "code_destinations",
  {
    id: text("id").primaryKey(),
    codeId: text("code_id")
      .notNull()
      .references(() => codes.id),
    destination: text("destination").notNull(),
    createdAt: integer("created_at").notNull(),
  },
  (t) => [index("code_destinations_code_id_idx").on(t.codeId, t.createdAt)],
);

/** No foreign key: the scan path must keep working regardless of the codes table. */
export const scans = sqliteTable(
  "scans",
  {
    /** Generated by redirect. Dedupes the queue's at-least-once delivery. */
    id: text("id").primaryKey(),
    shortCode: text("short_code").notNull(),
    scannedAt: integer("scanned_at").notNull(),
    country: text("country"),
    city: text("city"),
    deviceType: text("device_type", { enum: ["mobile", "desktop", "unknown"] }).notNull(),
  },
  (t) => [index("scans_short_code_idx").on(t.shortCode, t.scannedAt)],
);

/** Check results. Private by unguessable id; deleted by cron after 30 days. */
export const checks = sqliteTable(
  "checks",
  {
    id: text("id").primaryKey(),
    /** SHA-256 of the input, for the short-lived result cache. */
    inputHash: text("input_hash").notNull(),
    result: text("result").notNull(),
    createdAt: integer("created_at").notNull(),
  },
  (t) => [
    index("checks_input_hash_idx").on(t.inputHash, t.createdAt),
    index("checks_created_at_idx").on(t.createdAt),
  ],
);

export const providerReports = sqliteTable("provider_reports", {
  id: text("id").primaryKey(),
  providerSlug: text("provider_slug"),
  domain: text("domain"),
  message: text("message").notNull(),
  email: text("email"),
  status: text("status", { enum: ["open", "resolved"] })
    .notNull()
    .default("open"),
  createdAt: integer("created_at").notNull(),
});

/** Redirect domains seen by the checker but missing from the directory: the research queue. */
export const unknownDomains = sqliteTable(
  "unknown_domains",
  {
    domain: text("domain").notNull(),
    firstSeen: integer("first_seen").notNull(),
    lastSeen: integer("last_seen").notNull(),
    count: integer("count").notNull().default(1),
  },
  (t) => [primaryKey({ columns: [t.domain] })],
);
